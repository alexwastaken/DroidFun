// Collect a real native build. Never publishes or relabels older binaries.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
if (process.platform !== 'darwin') throw new Error('Run on macOS after native packaging');
const run = (cmd, args) => execFileSync(cmd, args, {encoding:'utf8'}).trim();
const version = JSON.parse(fs.readFileSync('package.json')).version;
const config = JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json'));
if (config.version !== version || config.productName !== 'DroidFun App') throw new Error('Unexpected package identity');
const release = path.join(process.env.CARGO_TARGET_DIR, 'universal-apple-darwin/release/bundle');
const app = path.join(release, 'macos/DroidFun App.app');
const plist = path.join(app,'Contents/Info.plist');
const installedVersion = run('/usr/libexec/PlistBuddy',['-c','Print :CFBundleShortVersionString',plist]);
const identifier = run('/usr/libexec/PlistBuddy',['-c','Print :CFBundleIdentifier',plist]);
if (installedVersion !== version || identifier !== config.identifier) throw new Error('Built bundle identity does not match source');
const binary = run('/usr/libexec/PlistBuddy',['-c','Print :CFBundleExecutable',plist]);
const architectures = run('lipo',['-archs',path.join(app,'Contents/MacOS',binary)]).split(/\s+/);
if (!architectures.includes('arm64') || !architectures.includes('x86_64')) throw new Error('Expected a universal Mac executable');
run('codesign',['--verify','--deep','--strict',app]);
const dmgs = fs.readdirSync(path.join(release,'dmg')).filter(f=>f.endsWith('.dmg'));
if (dmgs.length !== 1) throw new Error('Expected exactly one disk image');
fs.mkdirSync('packages',{recursive:true});
const prefix = `DroidFun-App-${version}-macOS-universal`;
const dmg = path.join('packages',`${prefix}.dmg`);
fs.copyFileSync(path.join(release,'dmg',dmgs[0]),dmg);
run('hdiutil',['verify',dmg]);
const zip = path.join('packages',`${prefix}.zip`);
run('ditto',['-c','-k','--sequesterRsrc','--keepParent',app,zip]);
const testLog = fs.readFileSync('packages/native-tests-macOS.txt','utf8');
const passed = Number(testLog.match(/test result: ok\. (\d+) passed; 0 failed/)?.[1]);
if (!(passed > 0)) throw new Error('Passing native tests are required');
const assets = [dmg,zip].map(file=>{const data=fs.readFileSync(file);return {name:path.basename(file),bytes:data.length,sha256:crypto.createHash('sha256').update(data).digest('hex')};});
const evidence = {version,productName:config.productName,identifier,applicationCommit:run('git',['rev-parse','HEAD']),architectures,tests:{passed,failed:0},adHocSignatureVerified:true,developerIdSigned:false,notarized:false,assets,remaining:['Local launch and upgrade verification','USB robot connection verification','Intel Mac runtime']};
fs.writeFileSync(`packages/verification-${version}-macOS.json`,JSON.stringify(evidence,null,2)+'\n');
fs.writeFileSync(`packages/SHA256SUMS-${version}-macOS.txt`,assets.map(a=>`${a.sha256}  ${a.name}`).join('\n')+'\n');
console.log(JSON.stringify(evidence,null,2));
